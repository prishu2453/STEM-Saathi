export function generateAllRemainingStateBoardRecords(): BoardSyllabusRecord[] {
  const classes: SchoolClass[] = [6, 7, 8, 9, 10, 11, 12];
  const records: BoardSyllabusRecord[] = [];

  for (const stateName of STATE_BOARD_STATES) {
    const meta = STATE_BOARD_META[stateName] ?? STATE_BOARD_META['Other Indian State / Board'];
    for (const classLevel of classes) {
      if (HANDCRAFTED_KEYS.has(`${stateName}-${classLevel}`)) {
        continue;
      }
      records.push({
        id: `state-${meta.slug}-c${classLevel}-2025-26`,
        classLevel,
        board: 'state',
        stateName,
        session: '2025-26',
        academicYearLabel: '2025–26',
        syllabusVersionLabel: `${meta.boardShort} · Class ${classLevel}`,
        textbookName:
          classLevel >= 11
            ? `${meta.higherSecBoard} Class ${classLevel} Physics, Chemistry & Biology`
            : `${meta.textbookSeries} Class ${classLevel} Science`,
        sourceTitle: meta.sourceTitle,
        sourceUrl: meta.sourceUrl,
        lastVerified: '2026-01-15',
        coverageNote: {
          en: `${meta.boardShort} Class ${classLevel} Physics, Chemistry & Biology chapters with interactive simulations and prescribed syllabus practicals.`,
        },
        availableSubjects: ['physics', 'chemistry', 'biology'],
        chapters: buildStateClassChapters(stateName, meta, classLevel),
      });
    }
  }

  return records;
}
